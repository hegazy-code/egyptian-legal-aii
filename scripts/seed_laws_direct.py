def setup_python_path(backend_dir: Path) -> None:
    """Add the backend directory to sys.path so we can import app.*"""
    backend_str = str(backend_dir.resolve())
    if backend_str not in sys.path:
        sys.path.insert(0, backend_str)


def seed(backend_dir: Path, verbose: bool = True) -> None:
    setup_python_path(backend_dir)

    # Lazy import after path setup
    from sqlalchemy import create_engine
    from sqlalchemy.orm import sessionmaker
    from app.config import settings
    from app.models.base import Base
    from app.models.legal import Source, Document, Law, Article

    engine = create_engine(settings.DATABASE_URL, echo=False)
    # Ensure tables exist (idempotent if migrations already ran)
    Base.metadata.create_all(bind=engine)
    Session = sessionmaker(bind=engine)
    session = Session()

    total_articles = 0

    try:
        for law_data in LAWS_DATA:
            src_data = law_data["source"]
            law_data_dict = law_data["law"]
            articles_data = law_data["articles"]

            # ---- Source (upsert by URL) ----
            existing_source = session.query(Source).filter_by(url=src_data["url"]).first()
            if existing_source:
                source = existing_source
                if verbose:
                    print(f"  Source already exists: {source.name}")
            else:
                source = Source(**src_data)
                session.add(source)
                session.flush()
                if verbose:
                    print(f"  Created source: {source.name}")

            # ---- Law (upsert by law_number + year) ----
            existing_law = session.query(Law).filter_by(
                law_number=law_data_dict["law_number"],
                year=law_data_dict["year"],
            ).first()

            if existing_law:
                law = existing_law
                if verbose:
                    print(f"  Law already seeded: {law.title} — skipping articles")
                continue

            law = Law(source_id=source.id, **law_data_dict)
            session.add(law)
            session.flush()

            if verbose:
                print(f"  Created law: {law.title}")

            # ---- Articles ----
            for a in articles_data:
                article = Article(
                    law_id=law.id,
                    article_number=a["number"],
                    text=a["text"],
                    chapter=a.get("chapter"),
                    section=a.get("section"),
                    order_index=a.get("order_index"),
                    status="active",
                )
                session.add(article)
                total_articles += 1

            if verbose:
                print(f"    Inserted {len(articles_data)} articles")

        session.commit()
        print(f"\n✓ Seeding complete. Total new articles inserted: {total_articles}")

    except Exception as exc:
        session.rollback()
        print(f"\n✗ Seeding failed: {exc}", file=sys.stderr)
        raise
    finally:
        session.close()


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Seed the database with Egyptian law articles directly (no PDF downloads needed)."
    )
    parser.add_argument(
        "--backend-dir",
        type=Path,
        default=Path(__file__).parent.parent / "backend",
        help="Path to the backend/ directory (default: ../backend relative to this script).",
    )
    parser.add_argument(
        "--quiet", "-q",
        action="store_true",
        help="Suppress per-record output.",
    )
    args = parser.parse_args()

    if not args.backend_dir.exists():
        print(f"ERROR: backend directory not found: {args.backend_dir}", file=sys.stderr)
        print("Use --backend-dir to specify the correct path.", file=sys.stderr)
        return 1

    print(f"Seeding Egyptian law data into database...")
    print(f"Backend dir: {args.backend_dir.resolve()}")
    print(f"Laws to seed: {len(LAWS_DATA)}\n")

    try:
        seed(args.backend_dir, verbose=not args.quiet)
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
