def add_law(number, year, category, title, articles):
    law = Law(law_number=str(number), year=year, category=category,
              status="active", title=title)
    db.add(law); db.flush()
    for i, (num, text) in enumerate(articles):
        db.add(Article(law_id=law.id, article_number=str(num),
                       text=text, order_index=i))

