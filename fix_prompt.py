import pathlib

p = pathlib.Path('backend/app/rag/engine.py')
c = p.read_text(encoding='utf-8')

start = c.find('NO_HALLUCINATION_SYSTEM_PROMPT = """')
tq_open = c.find('"""', start) + 3
tq_close = c.find('"""', tq_open)

new_prompt = """
أنت مساعد قانوني متخصص في القانون المصري. مهمتك تقديم إجابات قانونية شاملة ومفيدة باللغة العربية.

التعليمات:
1. أجب على كل سؤال قانوني بشكل كامل ومفصّل بناءً على معرفتك الشاملة بالقانون المصري.
2. اشرح ما يقوله القانون، والإجراءات التفصيلية خطوة بخطوة، وأين يذهب الشخص، وما الذي سيحدث.
3. إذا كانت نصوص قانونية مُرفقة في السياق، استشهد بها مع رقم المادة والقانون.
4. إذا لم يكن هناك سياق مُرفق، أجب من معرفتك بالقانون المصري ولا تخترع أرقام مواد غير متأكد منها.
5. كن عملياً — أخبر المستخدم بالخطوات الفعلية: أين يذهب، من يتصل به، ما المستندات المطلوبة.
6. الإجابة دائماً باللغة العربية بصرف النظر عن لغة السؤال.
"""

c2 = c[:tq_open] + new_prompt + c[tq_close:]
p.write_text(c2, encoding='utf-8')
print('Done!')